/* the next session event of a type, or 0 after the timeout */
static HRESULT wait_event(IMFMediaSession *session, MediaEventType want, DWORD timeout, BOOL *got)
{
    DWORD end = GetTickCount() + timeout;
    IMFMediaEvent *event;
    MediaEventType type;
    HRESULT hr, status = E_FAIL;

    *got = FALSE;
    while ((LONG)(end - GetTickCount()) > 0)
    {
        hr = IMFMediaSession_GetEvent(session, MF_EVENT_FLAG_NO_WAIT, &event);
        if (hr == MF_E_NO_EVENTS_AVAILABLE) { Sleep(10); continue; }
        if (FAILED(hr)) break;
        IMFMediaEvent_GetType(event, &type);
        IMFMediaEvent_GetStatus(event, &status);
        IMFMediaEvent_Release(event);
        if (type == want) { *got = TRUE; return status; }
    }
    return E_FAIL;
}

static IMFMediaSession *open_session(IMFMediaSource **ret_source)
{
    IMFTopologyNode *src_node, *sink_node;
    IMFStreamDescriptor *sd;
    IMFPresentationDescriptor *pd;
    IMFSourceResolver *resolver;
    IMFAttributes *attributes;
    IMFMediaSession *session;
    IMFMediaSource *source;
    IMFActivate *activate;
    IMFMediaType *type;
    IMFTopology *topology;
    IMFByteStream *stream;
    MF_OBJECT_TYPE obj_type;
    ULONG written;
    BOOL selected;
    HRESULT hr;

    MFCreateTempFile(MF_ACCESSMODE_READWRITE, MF_OPENMODE_DELETE_IF_EXIST, MF_FILEFLAGS_NONE, &stream);
    IMFByteStream_Write(stream, test_mp4, test_mp4_len, &written);
    IMFByteStream_SetCurrentPosition(stream, 0);
    IMFByteStream_QueryInterface(stream, &IID_IMFAttributes, (void **)&attributes);
    IMFAttributes_SetString(attributes, &MF_BYTESTREAM_CONTENT_TYPE, L"video/mp4");
    IMFAttributes_Release(attributes);
    MFCreateSourceResolver(&resolver);
    hr = IMFSourceResolver_CreateObjectFromByteStream(resolver, stream, NULL, MF_RESOLUTION_MEDIASOURCE, NULL,
            &obj_type, (IUnknown **)&source);
    IMFSourceResolver_Release(resolver);
    IMFByteStream_Release(stream);
    if (FAILED(hr)) { printf("info: no MP4 source (%#lx)\n", hr); return NULL; }

    MFCreateMediaType(&type);
    IMFMediaType_SetGUID(type, &MF_MT_MAJOR_TYPE, &MFMediaType_Video);
    IMFMediaType_SetGUID(type, &MF_MT_SUBTYPE, &MFVideoFormat_RGB32);
    MFCreateSampleGrabberSinkActivate(type, &grabber, &activate);
    IMFMediaType_Release(type);

    MFCreateTopology(&topology);
    MFCreateTopologyNode(MF_TOPOLOGY_OUTPUT_NODE, &sink_node);
    MFCreateTopologyNode(MF_TOPOLOGY_SOURCESTREAM_NODE, &src_node);
    IMFTopology_AddNode(topology, sink_node);
    IMFTopology_AddNode(topology, src_node);
    IMFTopologyNode_ConnectOutput(src_node, 0, sink_node, 0);
    IMFMediaSource_CreatePresentationDescriptor(source, &pd);
    IMFPresentationDescriptor_GetStreamDescriptorByIndex(pd, 0, &selected, &sd);
    IMFTopologyNode_SetUnknown(src_node, &MF_TOPONODE_SOURCE, (IUnknown *)source);
    IMFTopologyNode_SetUnknown(src_node, &MF_TOPONODE_PRESENTATION_DESCRIPTOR, (IUnknown *)pd);
    IMFTopologyNode_SetUnknown(src_node, &MF_TOPONODE_STREAM_DESCRIPTOR, (IUnknown *)sd);
    IMFTopologyNode_SetObject(sink_node, (IUnknown *)activate);
    IMFTopologyNode_SetUINT32(sink_node, &MF_TOPONODE_CONNECT_METHOD, MF_CONNECT_ALLOW_DECODER);
    IMFTopology_SetUINT32(topology, &MF_TOPOLOGY_ENUMERATE_SOURCE_TYPES_, TRUE);
    IMFStreamDescriptor_Release(sd);
    IMFPresentationDescriptor_Release(pd);
    IMFTopologyNode_Release(src_node);
    IMFTopologyNode_Release(sink_node);

    MFCreateMediaSession(NULL, &session);
    IMFMediaSession_SetTopology(session, 0, topology);
    IMFTopology_Release(topology);
    IMFActivate_Release(activate);
    *ret_source = source;
    return session;
}

enum action { START, SEEK, PAUSE, STOP };

int main(void)
{
    /* each step must give its event; where marked, samples must arrive after it */
    static const struct { const char *what; enum action action; LONGLONG position; MediaEventType event; BOOL samples; } steps[] =
    {
        {"start", START, 0, MESessionStarted, TRUE},
        {"stop", STOP, 0, MESessionStopped, FALSE},
        {"start after stop", START, 0, MESessionStarted, TRUE},
        {"pause", PAUSE, 0, MESessionPaused, FALSE},
        {"seek to 0s from pause", SEEK, 0, MESessionStarted, TRUE},
        {"stop again", STOP, 0, MESessionStopped, FALSE},
        {"start at 0s", SEEK, 0, MESessionStarted, TRUE},
    };
    IMFMediaSession *session;
    IMFMediaSource *source;
    PROPVARIANT pos;
    unsigned int i;
    BOOL got;
    HRESULT hr;

    MFStartup(MF_VERSION, MFSTARTUP_FULL);
    if (!(session = open_session(&source)))
    {
        check(0, "session made");
        printf("RESULT: FAIL\n");
        return 1;
    }
    for (i = 0; i < ARRAYSIZE(steps); i++)
    {
        LONG before = samples;

        PropVariantInit(&pos);
        if (steps[i].action == SEEK) { pos.vt = VT_I8; pos.hVal.QuadPart = steps[i].position; }
        if (steps[i].action == PAUSE) IMFMediaSession_Pause(session);
        else if (steps[i].action == STOP) IMFMediaSession_Stop(session);
        else IMFMediaSession_Start(session, &GUID_NULL, &pos);
        hr = wait_event(session, steps[i].event, 5000, &got);
        check(got && hr == S_OK, "%s: event %d, %#lx", steps[i].what, got, hr);
        if (steps[i].samples)
        {
            DWORD end = GetTickCount() + 3000;
            while (samples == before && (LONG)(end - GetTickCount()) > 0) Sleep(10);
            check(samples > before, "%s: samples arrive (%ld)", steps[i].what, samples - before);
        }
    }
    IMFMediaSession_Stop(session);
    wait_event(session, MESessionStopped, 3000, &got);
    IMFMediaSession_Close(session);
    wait_event(session, MESessionClosed, 3000, &got);
    IMFMediaSession_Shutdown(session);
    IMFMediaSource_Shutdown(source);
    IMFMediaSource_Release(source);
    IMFMediaSession_Release(session);
    MFShutdown();
    printf("RESULT: %s\n", failures ? "FAIL" : "PASS");
    return !!failures;
}
