static void say(const char *name, int ok, const char *fmt, ...)
{
    char buf[512];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    printf("%s=%d %s\n", name, ok ? 1 : 0, buf);
    fflush(stdout);
}

int main(void)
{
    IMFSourceResolver *resolver;
    IMFSourceReader *reader;
    IMFMediaType *type;
    IGraphBuilder *graph;
    MF_OBJECT_TYPE ot;
    IUnknown *obj;
    DWORD written, flags, stream;
    LONGLONG ts, last = -1;
    int samples = 0, eos = 0;
    HANDLE h;
    HRESULT hr;

    CoInitializeEx(NULL, COINIT_MULTITHREADED);
    MFStartup(MF_VERSION, 0);
    h = CreateFileA("C:\\tiny.ts", GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, 0, NULL);
    WriteFile(h, tiny_ts, sizeof(tiny_ts), &written, NULL);
    CloseHandle(h);
    say("write", written == sizeof(tiny_ts), "%lu bytes", written);

    MFCreateSourceResolver(&resolver);
    hr = IMFSourceResolver_CreateObjectFromURL(resolver, L"C:\\tiny.ts", MF_RESOLUTION_MEDIASOURCE, NULL, &ot, &obj);
    say("source", hr == S_OK, "media source %#lx", hr);
    if (SUCCEEDED(hr)) IUnknown_Release(obj);
    IMFSourceResolver_Release(resolver);

    hr = MFCreateSourceReaderFromURL(L"C:\\tiny.ts", NULL, &reader);
    say("reader", hr == S_OK, "source reader %#lx", hr);
    if (SUCCEEDED(hr))
    {
        MFCreateMediaType(&type);
        IMFMediaType_SetGUID(type, &MF_MT_MAJOR_TYPE, &MFMediaType_Audio);
        IMFMediaType_SetGUID(type, &MF_MT_SUBTYPE, &MFAudioFormat_PCM);
        hr = IMFSourceReader_SetCurrentMediaType(reader, MF_SOURCE_READER_FIRST_AUDIO_STREAM, NULL, type);
        IMFMediaType_Release(type);
        say("pcm", hr == S_OK, "PCM output %#lx", hr);
        while (samples < 1000)
        {
            IMFSample *sample = NULL;
            hr = IMFSourceReader_ReadSample(reader, MF_SOURCE_READER_FIRST_AUDIO_STREAM, 0, &stream, &flags, &ts, &sample);
            if (FAILED(hr) || (flags & MF_SOURCE_READERF_ERROR)) break;
            if (sample) { samples++; last = ts; IMFSample_Release(sample); }
            if (flags & MF_SOURCE_READERF_ENDOFSTREAM) { eos = 1; break; }
        }
        say("read", samples > 0 && eos && last >= 3000000, "%d samples, last at %I64d ms, end of stream %d (%#lx)",
                samples, last / 10000, eos, hr);
        IMFSourceReader_Release(reader);
    }

    CoCreateInstance(&CLSID_FilterGraph, NULL, CLSCTX_INPROC_SERVER, &IID_IGraphBuilder, (void **)&graph);
    hr = IGraphBuilder_RenderFile(graph, L"C:\\tiny.ts", NULL);
    say("render", hr == S_OK, "DirectShow RenderFile %#lx", hr);
    IGraphBuilder_Release(graph);

    fflush(stdout);
    TerminateProcess(GetCurrentProcess(), 0);
    return 0;
}
