static BOOL installed(IAssemblyCache *cache)
{
    WCHAR path[MAX_PATH] = L"";
    ASSEMBLY_INFO info = { sizeof(info) };
    HRESULT hr;

    info.pszCurrentAssemblyPathBuf = path;
    info.cchBuf = MAX_PATH;
    hr = IAssemblyCache_QueryAssemblyInfo(cache, 0, asm_name, &info);
    return hr == S_OK && path[0] && GetFileAttributesW(path) != INVALID_FILE_ATTRIBUTES;
}

static void write_stream(IStream *stream, const void *data, ULONG size)
{
    ULONG written = 0;
    HRESULT hr = IStream_Write(stream, data, size, &written);
    CHECK(hr == S_OK && written == size, "stream write %08lx %lu", hr, written);
}

static IAssemblyCacheItem *make_item(IAssemblyCache *cache, DWORD flags, BOOL with_manifest, BOOL with_module)
{
    IAssemblyCacheItem *item = NULL;
    IStream *stream;
    HRESULT hr;

    hr = IAssemblyCache_CreateAssemblyCacheItem(cache, flags, NULL, &item, NULL);
    CHECK(hr == S_OK && item, "create item %08lx", hr);
    if (!item) return NULL;
    if (with_manifest)
    {
        stream = NULL;
        hr = IAssemblyCacheItem_CreateStream(item, 0, L"wine.dll", STREAM_FORMAT_COMPLIB_MANIFEST, 0, &stream, NULL);
        CHECK(hr == S_OK && stream, "manifest stream %08lx", hr);
        if (stream)
        {
            write_stream(stream, fixture, sizeof(fixture));
            IStream_Release(stream);
        }
    }
    if (with_module)
    {
        stream = NULL;
        hr = IAssemblyCacheItem_CreateStream(item, 0, L"module.netmodule", STREAM_FORMAT_COMPLIB_MODULE, 0, &stream, NULL);
        CHECK(hr == S_OK && stream, "module stream %08lx", hr);
        if (stream) IStream_Release(stream);
    }
    return item;
}

static void test_cache_item(void)
{
    IAssemblyCache *cache;
    IAssemblyCacheItem *item;
    IStream *stream;
    ULONG disp;
    HRESULT hr;

    hr = pCreateAssemblyCache(&cache, 0);
    CHECK(hr == S_OK, "cache %08lx", hr);
    IAssemblyCache_UninstallAssembly(cache, 0, asm_name, NULL, NULL);
    CHECK(!installed(cache), "not installed at the start");

    /* the stream arguments */
    item = NULL;
    hr = IAssemblyCache_CreateAssemblyCacheItem(cache, 0, NULL, &item, NULL);
    CHECK(hr == S_OK, "item %08lx", hr);
    stream = (IStream *)1;
    hr = IAssemblyCacheItem_CreateStream(item, 0, NULL, 1, 0, &stream, NULL);
    CHECK(hr == E_INVALIDARG && stream == NULL, "no name %08lx", hr);
    hr = IAssemblyCacheItem_CreateStream(item, 0, L"a\\b.dll", 1, 0, &stream, NULL);
    CHECK(hr == E_INVALIDARG, "path as name %08lx", hr);
    hr = IAssemblyCacheItem_CreateStream(item, 0, L"x.dll", 77, 0, &stream, NULL);
    CHECK(hr == E_INVALIDARG, "wrong format %08lx", hr);
    hr = IAssemblyCacheItem_CreateStream(item, 0, L"x.dll", 1, 0, NULL, NULL);
    CHECK(hr == E_INVALIDARG, "no stream pointer %08lx", hr);
    /* nothing to commit without the manifest */
    hr = IAssemblyCacheItem_CreateStream(item, 0, L"x.netmodule", 0, 0, &stream, NULL);
    CHECK(hr == S_OK && stream, "module %08lx", hr);
    if (stream) IStream_Release(stream);
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == E_FAIL, "commit without manifest %08lx", hr);
    hr = IAssemblyCacheItem_Commit(item, 0x100, &disp);
    CHECK(hr == E_INVALIDARG, "commit flags %08lx", hr);
    hr = IAssemblyCacheItem_AbortItem(item);
    CHECK(hr == S_OK, "abort %08lx", hr);
    hr = IAssemblyCacheItem_AbortItem(item);
    CHECK(hr == E_UNEXPECTED, "abort twice %08lx", hr);
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == E_UNEXPECTED, "commit after abort %08lx", hr);
    stream = (IStream *)1;
    hr = IAssemblyCacheItem_CreateStream(item, 0, L"y.dll", 1, 0, &stream, NULL);
    CHECK(hr == E_UNEXPECTED && stream == NULL, "stream after abort %08lx", hr);
    IAssemblyCacheItem_Release(item);
    CHECK(!installed(cache), "an aborted item installs nothing");

    /* a name that is not a display name */
    item = (IAssemblyCacheItem *)1;
    hr = IAssemblyCache_CreateAssemblyCacheItem(cache, 0, NULL, &item, L"a b");
    CHECK(hr == FUSION_E_INVALID_NAME && item == NULL, "bad name %08lx", hr);

    /* commit */
    item = make_item(cache, 0, TRUE, FALSE);
    disp = 0;
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == S_OK && disp == IASSEMBLYCACHEITEM_COMMIT_DISPOSITION_INSTALLED, "commit %08lx disp %lu", hr, disp);
    CHECK(installed(cache), "installed by the commit");
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == E_UNEXPECTED, "commit twice %08lx", hr);
    hr = IAssemblyCacheItem_AbortItem(item);
    CHECK(hr == E_UNEXPECTED, "abort after commit %08lx", hr);
    IAssemblyCacheItem_Release(item);

    /* again: it is there */
    item = make_item(cache, 0, TRUE, FALSE);
    disp = 0;
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == S_OK && disp == IASSEMBLYCACHEITEM_COMMIT_DISPOSITION_ALREADY_INSTALLED, "commit again %08lx disp %lu", hr, disp);
    IAssemblyCacheItem_Release(item);
    item = make_item(cache, 0, TRUE, FALSE);
    disp = 0;
    hr = IAssemblyCacheItem_Commit(item, IASSEMBLYCACHEITEM_COMMIT_FLAG_REFRESH, &disp);
    CHECK(hr == S_OK && disp == IASSEMBLYCACHEITEM_COMMIT_DISPOSITION_REFRESHED, "commit refresh %08lx disp %lu", hr, disp);
    IAssemblyCacheItem_Release(item);
    item = make_item(cache, IASSEMBLYCACHE_INSTALL_FLAG_FORCE_REFRESH, TRUE, FALSE);
    hr = IAssemblyCacheItem_Commit(item, 0, &disp);
    CHECK(hr == S_OK && disp == IASSEMBLYCACHEITEM_COMMIT_DISPOSITION_REFRESHED, "commit force refresh from creation %08lx disp %lu", hr, disp);
    IAssemblyCacheItem_Release(item);

    /* an item that is released is dropped */
    IAssemblyCache_UninstallAssembly(cache, 0, asm_name, NULL, NULL);
    CHECK(!installed(cache), "uninstalled");
    item = make_item(cache, 0, TRUE, FALSE);
    IAssemblyCacheItem_Release(item);
    CHECK(!installed(cache), "a released item installs nothing");
    IAssemblyCache_Release(cache);
}

