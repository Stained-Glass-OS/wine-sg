static int fails;
static void check(const char *name, int ok) { printf("      %s  %s\n", ok ? "PASS" : "FAIL", name); if (!ok) fails++; }

static LONG verify(const WCHAR *path, DWORD provflags)
{
    GUID action = WINTRUST_ACTION_GENERIC_VERIFY_V2;
    WINTRUST_FILE_INFO fi = { sizeof(fi), (WCHAR *)path };
    WINTRUST_DATA d = { sizeof(d) };
    LONG ret;
    d.dwUIChoice = WTD_UI_NONE;
    d.fdwRevocationChecks = WTD_REVOKE_NONE;
    d.dwUnionChoice = WTD_CHOICE_FILE;
    d.pFile = &fi;
    d.dwStateAction = WTD_STATEACTION_VERIFY;
    d.dwProvFlags = provflags;
    ret = WinVerifyTrust(NULL, &action, &d);
    d.dwStateAction = WTD_STATEACTION_CLOSE;
    WinVerifyTrust(NULL, &action, &d);
    return ret;
}

int main(void)
{
    WCHAR path[MAX_PATH];
    HANDLE h;
    DWORD n, i;
    BYTE bad[sizeof(signed_pe)];
    LONG r;

    GetTempPathW(MAX_PATH, path);
    wcscat(path, L"sg2437.exe");
    h = CreateFileW(path, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, 0, NULL);
    WriteFile(h, signed_pe, sizeof(signed_pe), &n, NULL);
    CloseHandle(h);

    r = verify(path, 0);
    printf("      (untrusted self-signed: %08lx)\n", (unsigned long)r);
    check("self-signed is not trusted", r == (LONG)CERT_E_CHAINING || r == (LONG)CERT_E_UNTRUSTEDROOT);
    r = verify(path, WTD_HASH_ONLY_FLAG);
    check("hash only: certificate not judged", r == 0);

    /* damage a byte of the code: the hash no longer matches in either mode */
    memcpy(bad, signed_pe, sizeof(bad));
    for (i = 0x200; i < 0x210; i++) bad[i] ^= 0xff;
    h = CreateFileW(path, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, 0, NULL);
    WriteFile(h, bad, sizeof(bad), &n, NULL);
    CloseHandle(h);
    r = verify(path, WTD_HASH_ONLY_FLAG);
    printf("      (damaged, hash only: %08lx)\n", (unsigned long)r);
    check("hash only still catches a changed file", r != 0);

    DeleteFileW(path);
    puts(fails ? "RESULT: FAIL" : "RESULT: PASS");
    return fails != 0;
}
