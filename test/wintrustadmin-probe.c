static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("FAIL  " __VA_ARGS__); printf("\n"); } } while (0)

static void write_file(const char *name, const void *data, DWORD size)
{
    HANDLE f = CreateFileA(name, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, 0, NULL);
    DWORD written;
    WriteFile(f, data, size, &written, NULL);
    CloseHandle(f);
}

int main(void)
{
    GUID sys = { 0xdeadbeef, 0xdead, 0xbeef, { 0xde, 0xad, 0xbe, 0xef, 0xde, 0xad, 0xbe, 0xef } };
    HCATADMIN admin;
    HCATINFO info;
    CATALOG_INFO ci = { sizeof(ci) };
    WCHAR *empty = (WCHAR *)L"empty.cat", *valid = (WCHAR *)L"valid.cat", *garbage = (WCHAR *)L"garbage.cat";
    WCHAR *named = (WCHAR *)L"sgprobe.cat", *p;
    DWORD err;
    BOOL ret;

    write_file("empty.cat", "", 0);
    write_file("valid.cat", sample_cat, sizeof(sample_cat));
    write_file("garbage.cat", "this is not a catalog at all, not even close", 44);

    ret = CryptCATAdminAcquireContext(&admin, &sys, 0);
    CHECK(ret, "acquire %lu", GetLastError());
    if (!ret) { printf("RESULT: FAIL\n"); return 1; }

    /* arguments first, then the file */
    SetLastError(0xdeadbeef);
    CHECK(!CryptCATAdminAddCatalog(NULL, NULL, NULL, 0) && GetLastError() == ERROR_INVALID_PARAMETER, "NULL everything");
    SetLastError(0xdeadbeef);
    CHECK(!CryptCATAdminAddCatalog(admin, NULL, NULL, 0) && GetLastError() == ERROR_INVALID_PARAMETER, "no file");
    SetLastError(0xdeadbeef);
    CHECK(!CryptCATAdminAddCatalog(admin, valid, named, 1) && GetLastError() == ERROR_INVALID_PARAMETER, "flags");

    /* a file with nothing in it, or nothing a catalog is */
    SetLastError(0xdeadbeef);
    info = CryptCATAdminAddCatalog(admin, empty, named, 0);
    err = GetLastError();
    CHECK(!info && err == ERROR_BAD_FORMAT, "empty file with a name: %p %lu", info, err);
    SetLastError(0xdeadbeef);
    info = CryptCATAdminAddCatalog(admin, empty, NULL, 0);
    err = GetLastError();
    CHECK(!info && err == ERROR_BAD_FORMAT, "empty file without a name: %p %lu", info, err);
    SetLastError(0xdeadbeef);
    info = CryptCATAdminAddCatalog(admin, garbage, named, 0);
    err = GetLastError();
    CHECK(!info && err == ERROR_BAD_FORMAT, "garbage file: %p %lu", info, err);

    /* a catalog without a name asked for: one is made up, and it is not the same twice */
    info = CryptCATAdminAddCatalog(admin, valid, NULL, 0);
    CHECK(info != NULL, "valid catalog without a name: %lu", GetLastError());
    if (info)
    {
        WCHAR first[MAX_PATH], second[MAX_PATH];
        HCATINFO info2;

        ci.wszCatalogFile[0] = 0;
        CHECK(CryptCATCatalogInfoFromContext(info, &ci, 0) && ci.wszCatalogFile[0], "info from context %lu", GetLastError());
        lstrcpyW(first, ci.wszCatalogFile);
        CHECK(GetFileAttributesW(first) != INVALID_FILE_ATTRIBUTES, "catalog %ls was not copied", first);
        p = wcsrchr(first, '\\');
        CHECK(p && wcslen(p + 1) > 4 && !_wcsicmp(p + wcslen(p) - 4, L".cat"), "made-up name %ls", p ? p : first);

        info2 = CryptCATAdminAddCatalog(admin, valid, NULL, 0);
        CHECK(info2 != NULL, "second add");
        if (info2)
        {
            ci.wszCatalogFile[0] = 0;
            CryptCATCatalogInfoFromContext(info2, &ci, 0);
            lstrcpyW(second, ci.wszCatalogFile);
            CHECK(wcscmp(first, second), "the same name twice: %ls", first);
            CryptCATAdminReleaseCatalogContext(admin, info2, 0);
            p = wcsrchr(second, '\\');
            if (p) CHECK(CryptCATAdminRemoveCatalog(admin, p + 1, 0), "remove second %lu", GetLastError());
        }
        CryptCATAdminReleaseCatalogContext(admin, info, 0);
        p = wcsrchr(first, '\\');
        if (p) CHECK(CryptCATAdminRemoveCatalog(admin, p + 1, 0), "remove first %lu", GetLastError());
        CHECK(GetFileAttributesW(first) == INVALID_FILE_ATTRIBUTES, "made-up catalog not removed");
    }
    CryptCATAdminReleaseContext(admin, 0);

    /* putting a signature into a handle that is only for reading */
    {
        GUID pe = { 0xC689AAB8, 0x8E78, 0x11D0, { 0x8C,0x47,0x00,0xC0,0x4F,0xC2,0x95,0xEE } };
        SIP_SUBJECTINFO si = { sizeof(si) };
        DWORD index = 0;
        HANDLE file;

        write_file("image.exe", sample_cat, 64);
        file = CreateFileA("image.exe", GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
        si.pgSubjectType = &pe;
        si.hFile = file;
        si.pwsFileName = L"image.exe";
        SetLastError(0xdeadbeef);
        ret = CryptSIPPutSignedDataMsg(&si, X509_ASN_ENCODING, &index, 4, (BYTE *)"test");
        CHECK(!ret && GetLastError() == ERROR_INVALID_PARAMETER, "put into a read-only handle: %d %lu", ret, GetLastError());
        CloseHandle(file);
        DeleteFileA("image.exe");
    }

    DeleteFileA("empty.cat");
    DeleteFileA("valid.cat");
    DeleteFileA("garbage.cat");
    printf(failures ? "RESULT: FAIL\n" : "RESULT: PASS\n");
    return failures != 0;
}
