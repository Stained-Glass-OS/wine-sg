static int close_enough(const char *name, double got, double want, int is_float)
{
    int osc = !strcmp(name, "cyl_bessel_j") || !strcmp(name, "cyl_neumann") || !strncmp(name, "sph_bessel", 10) ||
              !strncmp(name, "sph_neumann", 11);
    double rel = is_float ? 1e-6 : (osc ? 1e-9 : 1e-11), abs_tol = is_float ? 1e-7 : 1e-14;

    if (isnan(want)) return isnan(got);
    if (isinf(want)) return got == want;
    if (want == 0.0) return fabs(got) <= abs_tol;
    if (is_float && fabs(want) > 3.4e38) return isinf(got);
    if (is_float && fabs(want) < 1e-37) return fabs(got) < 1e-30;
    return fabs(got - want) <= rel * fabs(want) || (osc && fabs(got - want) <= abs_tol);
}

