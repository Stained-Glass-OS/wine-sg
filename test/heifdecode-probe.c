static int close_to( const BYTE *p, int r, int g, int b )
{
    return abs( p[2] - r ) < 40 && abs( p[1] - g ) < 40 && abs( p[0] - b ) < 40;
}

static int check_decoder( IWICBitmapDecoder *decoder, const char *what )
{
    IWICBitmapFrameDecode *frame;
    WICPixelFormatGUID format;
    GUID container;
    UINT w = 0, h = 0, count = 0;
    static BYTE pixels[64 * 64 * 4];
    int ok;

    IWICBitmapDecoder_GetContainerFormat( decoder, &container );
    IWICBitmapDecoder_GetFrameCount( decoder, &count );
    if (FAILED(IWICBitmapDecoder_GetFrame( decoder, 0, &frame ))) { printf( "%s_frame=0\n", what ); return 0; }
    IWICBitmapFrameDecode_GetSize( frame, &w, &h );
    IWICBitmapFrameDecode_GetPixelFormat( frame, &format );
    ok = w == 64 && h == 64 && SUCCEEDED(IWICBitmapFrameDecode_CopyPixels( frame, NULL, 64 * 4, sizeof(pixels), pixels ));
    printf( "%s container_heif=%d frames=%u size=%ux%u bgr32=%d\n", what, IsEqualGUID( &container, &GUID_ContainerHeif_ ),
            count, w, h, IsEqualGUID( &format, &GUID_WICPixelFormat32bppBGR ) );
    /* the quadrants' centres: red, green / blue, white */
    ok = ok && close_to( pixels + (16 * 64 + 16) * 4, 220, 30, 30 ) && close_to( pixels + (16 * 64 + 48) * 4, 30, 200, 30 )
            && close_to( pixels + (48 * 64 + 16) * 4, 30, 30, 220 ) && close_to( pixels + (48 * 64 + 48) * 4, 240, 240, 240 );
    printf( "%s_pixels=%d\n", what, ok );
    IWICBitmapFrameDecode_Release( frame );
    return ok;
}

int main( void )
{
    IWICImagingFactory *factory;
    IWICBitmapDecoder *decoder;
    IWICComponentInfo *info;
    IWICBitmapCodecInfo *codec;
    IStream *stream;
    WCHAR ext[256] = {0};
    UINT len = 0;
    HANDLE file;
    DWORD written;
    HRESULT hr;

    setvbuf( stdout, NULL, _IONBF, 0 );
    CoInitializeEx( NULL, COINIT_APARTMENTTHREADED );
    file = CreateFileW( L"C:\\probe.heic", GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, 0, NULL );
    WriteFile( file, heic, sizeof(heic), &written, NULL );
    CloseHandle( file );

    hr = CoCreateInstance( &CLSID_WICImagingFactory, NULL, CLSCTX_INPROC_SERVER, &IID_IWICImagingFactory, (void **)&factory );
    if (FAILED(hr)) { printf( "factory=0 hr=%#lx\n", hr ); return 1; }

    hr = IWICImagingFactory_CreateComponentInfo( factory, &CLSID_HeifDecoder_, &info );
    if (SUCCEEDED(hr) && SUCCEEDED(IWICComponentInfo_QueryInterface( info, &IID_IWICBitmapCodecInfo, (void **)&codec )))
    {
        IWICBitmapCodecInfo_GetFileExtensions( codec, ARRAYSIZE(ext), ext, &len );
        IWICBitmapCodecInfo_Release( codec );
    }
    printf( "registered=%d extensions=%ls\n", SUCCEEDED(hr) && wcsstr( ext, L".heic" ) != NULL, ext );

    hr = IWICImagingFactory_CreateDecoderFromFilename( factory, L"C:\\probe.heic", NULL, GENERIC_READ,
                                                       WICDecodeMetadataCacheOnDemand, &decoder );
    printf( "file_hr=%#lx\n", hr );
    if (SUCCEEDED(hr)) { check_decoder( decoder, "file" ); IWICBitmapDecoder_Release( decoder ); }

    stream = SHCreateMemStream( heic, sizeof(heic) );
    hr = IWICImagingFactory_CreateDecoderFromStream( factory, stream, NULL, WICDecodeMetadataCacheOnDemand, &decoder );
    printf( "stream_hr=%#lx\n", hr );
    if (SUCCEEDED(hr)) { check_decoder( decoder, "stream" ); IWICBitmapDecoder_Release( decoder ); }
    IStream_Release( stream );

    /* the shell's thumbnail (the file type's thumbnail handler over WIC) */
    {
        IShellItemImageFactory *images;
        SIZE size = { 32, 32 };
        HBITMAP bitmap = NULL;
        BITMAP bm = { 0 };

        hr = SHCreateItemFromParsingName( L"C:\\probe.heic", NULL, &IID_IShellItemImageFactory, (void **)&images );
        if (SUCCEEDED(hr))
        {
            hr = IShellItemImageFactory_GetImage( images, size, SIIGBF_THUMBNAILONLY, &bitmap );
            IShellItemImageFactory_Release( images );
        }
        if (bitmap) GetObjectW( bitmap, sizeof(bm), &bm );
        printf( "thumbnail=%d hr=%#lx size=%ldx%ld\n", SUCCEEDED(hr) && bm.bmWidth == 32 && bm.bmHeight == 32, hr, bm.bmWidth, bm.bmHeight );
    }
    printf( "done=1\n" );
    return 0;
}
