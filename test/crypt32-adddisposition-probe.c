int main(void)
{
    static const DWORD bad[] = {8, 99, 0x80000000};
    HCERTSTORE store = CertOpenStore(CERT_STORE_PROV_MEMORY, 0, 0, 0, NULL);
    unsigned int i;
    BOOL ret;

    for (i = 0; i < ARRAYSIZE(bad); i++)
    {
        SetLastError(0xdeadbeef);
        ret = CertAddEncodedCRLToStore(store, X509_ASN_ENCODING, signedCRL, sizeof(signedCRL), bad[i], NULL);
        check(!ret && GetLastError() == E_INVALIDARG, "CRL, disposition %#lx: %d %#lx", bad[i], ret, GetLastError());
        SetLastError(0xdeadbeef);
        ret = CertAddEncodedCTLToStore(store, X509_ASN_ENCODING, signedCTLWithCTLInnerContent, sizeof(signedCTLWithCTLInnerContent),
                                       bad[i], NULL);
        check(!ret && GetLastError() == E_INVALIDARG, "CTL, disposition %#lx: %d %#lx", bad[i], ret, GetLastError());
    }
    ret = CertAddEncodedCRLToStore(store, X509_ASN_ENCODING, signedCRL, sizeof(signedCRL), CERT_STORE_ADD_ALWAYS, NULL);
    check(ret, "CRL, CERT_STORE_ADD_ALWAYS: %d %#lx", ret, ret ? 0 : GetLastError());
    ret = CertAddEncodedCTLToStore(store, X509_ASN_ENCODING, signedCTLWithCTLInnerContent, sizeof(signedCTLWithCTLInnerContent),
                                   CERT_STORE_ADD_ALWAYS, NULL);
    check(ret, "CTL, CERT_STORE_ADD_ALWAYS: %d %#lx", ret, ret ? 0 : GetLastError());
    CertCloseStore(store, 0);
    printf("RESULT: %s\n", failures ? "FAIL" : "PASS");
    return !!failures;
}
